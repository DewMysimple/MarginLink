import * as esbuild from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';
const options = {
  entryPoints: ['src/main.ts'], bundle: true, format: 'cjs', target: 'es2022',
  platform: 'browser', outfile: 'main.js', sourcemap: false,
  external: ['obsidian', '@codemirror/state', '@codemirror/view'],
  banner: { js: '/* MarginLink — native Wikilinks only. Generated by esbuild. */' },
  minify: false, logLevel: 'info', metafile: true
};
if (process.argv.includes('--watch')) {
  const context = await esbuild.context(options);
  await context.watch();
} else {
  const result = await esbuild.build(options);
  await mkdir('artifacts', { recursive: true });
  await writeFile('artifacts/bundle-meta.json', JSON.stringify(result.metafile));
}
